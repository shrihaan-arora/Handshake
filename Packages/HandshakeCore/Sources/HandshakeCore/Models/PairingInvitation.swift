import Foundation

public enum PairingInvitationError: Error, LocalizedError, Equatable {
    case invalidURL
    case invalidSchemeOrHost
    case unsupportedVersion(String)
    case missingRequiredField(String)
    case invalidUUID(String)
    case invalidKeyFormat(String)
    case invalidPort(String)
    case expired(Date)
    case malformedData

    public var errorDescription: String? {
        switch self {
        case .invalidURL:
            return "The scanned QR code is not a valid URL or payload."
        case .invalidSchemeOrHost:
            return "The scanned QR code is not a Handshake pairing invitation."
        case .unsupportedVersion(let v):
            return "Unsupported pairing protocol version '\(v)'."
        case .missingRequiredField(let field):
            return "Pairing invitation is missing required parameter '\(field)'."
        case .invalidUUID(let val):
            return "Pairing invitation has invalid session ID '\(val)'."
        case .invalidKeyFormat(let key):
            return "Pairing invitation contains invalid cryptographic key '\(key)'."
        case .invalidPort(let port):
            return "Pairing invitation contains invalid port '\(port)'."
        case .expired(let date):
            return "Pairing invitation expired at \(date)."
        case .malformedData:
            return "Pairing invitation data is corrupt or malformed."
        }
    }
}

/// Short-lived, single-use pairing invitation generated by the host Mac.
/// Rendered as a QR code and scanned by the client iPhone.
/// NEVER contains private keys or long-term secrets.
public struct PairingInvitation: Codable, Sendable, Identifiable, Equatable {
    public let id: UUID
    public let hostIdentity: DeviceIdentity
    public let ephemeralPublicKeyHex: String
    public let localPort: UInt16
    public let serviceName: String
    public let nonce: String
    public let createdAt: Date
    public let expiresAt: Date
    public let verificationCode: String

    public init(
        id: UUID = UUID(),
        hostIdentity: DeviceIdentity,
        ephemeralPublicKeyHex: String,
        localPort: UInt16 = 5894,
        serviceName: String = "Handshake-Host",
        nonce: String = UUID().uuidString,
        createdAt: Date = Date(),
        lifetimeSeconds: TimeInterval = 120,
        verificationCode: String = "849201"
    ) {
        self.id = id
        self.hostIdentity = hostIdentity
        self.ephemeralPublicKeyHex = ephemeralPublicKeyHex
        self.localPort = localPort
        self.serviceName = serviceName
        self.nonce = nonce
        self.createdAt = createdAt
        self.expiresAt = createdAt.addingTimeInterval(lifetimeSeconds)
        self.verificationCode = verificationCode
    }

    public init(
        id: UUID = UUID(),
        hostIdentity: DeviceIdentity,
        ephemeralPublicKeyHex: String,
        localPort: UInt16 = 5894,
        serviceName: String = "Handshake-Host",
        nonce: String = UUID().uuidString,
        createdAt: Date = Date(),
        expiresAt: Date,
        verificationCode: String = "849201"
    ) {
        self.id = id
        self.hostIdentity = hostIdentity
        self.ephemeralPublicKeyHex = ephemeralPublicKeyHex
        self.localPort = localPort
        self.serviceName = serviceName
        self.nonce = nonce
        self.createdAt = createdAt
        self.expiresAt = expiresAt
        self.verificationCode = verificationCode
    }

    /// Determines if the invitation has exceeded its security window.
    public func isExpired(at date: Date = Date()) -> Bool {
        date > expiresAt
    }

    /// Remaining validity duration in seconds. Resilient against non-finite or extreme dates.
    public func remainingSeconds(at date: Date = Date()) -> Int {
        let remaining = expiresAt.timeIntervalSince(date)
        guard remaining.isFinite, remaining > 0 else { return 0 }
        guard remaining < Double(Int.max) else { return Int.max }
        return Int(remaining)
    }

    /// URL-formatted string for QR code generation. Resilient against non-finite epoch conversions.
    public var qrPayloadString: String {
        var components = URLComponents()
        components.scheme = "handshake"
        components.host = "pair"
        let expSeconds = expiresAt.timeIntervalSince1970
        let expValue: String
        if expSeconds.isFinite && expSeconds > 0 && expSeconds < Double(Int.max) {
            expValue = String(Int(expSeconds))
        } else {
            expValue = "0"
        }
        components.queryItems = [
            URLQueryItem(name: "v", value: "1"),
            URLQueryItem(name: "id", value: id.uuidString),
            URLQueryItem(name: "name", value: hostIdentity.displayName),
            URLQueryItem(name: "pk", value: hostIdentity.publicKeyHex),
            URLQueryItem(name: "epk", value: ephemeralPublicKeyHex),
            URLQueryItem(name: "port", value: String(localPort)),
            URLQueryItem(name: "nonce", value: nonce),
            URLQueryItem(name: "exp", value: expValue),
            URLQueryItem(name: "code", value: verificationCode)
        ]
        return components.url?.absoluteString ?? "handshake://pair?id=\(id.uuidString)"
    }

    /// Parses and validates a QR code string or JSON payload into a verified `PairingInvitation`.
    /// Rejects expired invitations, malformed URLs, unsupported versions, and invalid cryptographic keys.
    public static func parse(from rawString: String, currentDate: Date = Date()) throws -> PairingInvitation {
        let trimmed = rawString.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { throw PairingInvitationError.malformedData }

        // 1. JSON fallback decoding
        if trimmed.hasPrefix("{") && trimmed.hasSuffix("}") {
            guard let jsonData = trimmed.data(using: .utf8) else {
                throw PairingInvitationError.malformedData
            }
            do {
                let invitation = try JSONDecoder().decode(PairingInvitation.self, from: jsonData)
                if invitation.isExpired(at: currentDate) {
                    throw PairingInvitationError.expired(invitation.expiresAt)
                }
                guard !invitation.hostIdentity.publicKeyHex.isEmpty,
                      Data(hexString: invitation.hostIdentity.publicKeyHex) != nil,
                      !invitation.ephemeralPublicKeyHex.isEmpty,
                      Data(hexString: invitation.ephemeralPublicKeyHex) != nil else {
                    throw PairingInvitationError.invalidKeyFormat("publicKey")
                }
                return invitation
            } catch let error as PairingInvitationError {
                throw error
            } catch {
                throw PairingInvitationError.malformedData
            }
        }

        // 2. URL Scheme decoding
        guard let url = URL(string: trimmed),
              let components = URLComponents(url: url, resolvingAgainstBaseURL: false) else {
            throw PairingInvitationError.invalidURL
        }

        guard components.scheme?.lowercased() == "handshake",
              components.host?.lowercased() == "pair" else {
            throw PairingInvitationError.invalidSchemeOrHost
        }

        var queryMap: [String: String] = [:]
        for item in components.queryItems ?? [] {
            queryMap[item.name] = item.value
        }

        // Validate protocol version
        guard let version = queryMap["v"] else {
            throw PairingInvitationError.missingRequiredField("v")
        }
        guard version == "1" else {
            throw PairingInvitationError.unsupportedVersion(version)
        }

        // Validate invitation UUID
        guard let idString = queryMap["id"], let id = UUID(uuidString: idString) else {
            throw PairingInvitationError.invalidUUID(queryMap["id"] ?? "missing")
        }

        // Validate host identity parameters
        guard let name = queryMap["name"], !name.isEmpty else {
            throw PairingInvitationError.missingRequiredField("name")
        }

        guard let pk = queryMap["pk"], !pk.isEmpty, Data(hexString: pk) != nil else {
            throw PairingInvitationError.invalidKeyFormat("pk")
        }

        guard let epk = queryMap["epk"], !epk.isEmpty, Data(hexString: epk) != nil else {
            throw PairingInvitationError.invalidKeyFormat("epk")
        }

        let port: UInt16
        if let portString = queryMap["port"] {
            guard let parsedPort = UInt16(portString), parsedPort > 0 else {
                throw PairingInvitationError.invalidPort(portString)
            }
            port = parsedPort
        } else {
            port = 5894
        }

        guard let nonce = queryMap["nonce"], !nonce.isEmpty else {
            throw PairingInvitationError.missingRequiredField("nonce")
        }

        guard let expString = queryMap["exp"], let expEpoch = Double(expString), expEpoch > 0 else {
            throw PairingInvitationError.missingRequiredField("exp")
        }

        let expiresAt = Date(timeIntervalSince1970: expEpoch)
        if expiresAt < currentDate {
            throw PairingInvitationError.expired(expiresAt)
        }

        let serviceName = queryMap["svc"] ?? "Handshake-Host"
        let verificationCode = queryMap["code"] ?? "849201"

        let hostIdentity = DeviceIdentity(
            id: UUID(),
            publicKeyHex: pk,
            displayName: name,
            deviceType: .mac,
            modelIdentifier: "Mac",
            systemVersion: "macOS",
            createdAt: Date()
        )

        return PairingInvitation(
            id: id,
            hostIdentity: hostIdentity,
            ephemeralPublicKeyHex: epk,
            localPort: port,
            serviceName: serviceName,
            nonce: nonce,
            createdAt: expiresAt.addingTimeInterval(-120),
            expiresAt: expiresAt,
            verificationCode: verificationCode
        )
    }
}
